/* Packs the example songs listed in examples/catalog.json for the page:
     examples/index.js         the gallery: title, style, tags, tempo, length, key, date and a small map of
                               the arrangement for every song (no notes, so it stays small as the list grows)
     examples/songs/<id>.js    one file per song with the full project, loaded only when that song is opened
   Scripts (unlike fetch) also work when index.html is opened straight from disk.
   Run after adding or changing an example:  node tools/pack-examples.js

   A catalog entry: { "id", "file", "title", "style", "blurb", "added": "YYYY-MM-DD", "tags": ["house", ...] }
   id is what ?example=<id> opens; tags are short, lowercase genre or mood words, reused where they fit. */
'use strict';
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'examples');
const HEAD = '/* Generated by tools/pack-examples.js from examples/catalog.json and the song files. Do not edit. */\n';
const ID = /^[a-z0-9][a-z0-9-]*$/;

const readCatalog = () => JSON.parse(fs.readFileSync(path.join(dir, 'catalog.json'), 'utf8'));

function songSecs(project, end) {
  // follow the song's tempo changes: from beat b on it plays at bpm
  const changes = (project.tempo || []).filter((c) => c.b < end).sort((x, y) => x.b - y.b);
  let secs = 0, at = 0, bpm = project.bpm;
  for (const c of changes) { secs += ((c.b - at) * 60) / bpm; at = c.b; bpm = c.bpm; }
  return Math.round(secs + ((end - at) * 60) / bpm);
}

/* The arrangement at a glance: per track its colour and the bars where it plays, as [startBar, bars] runs. */
function songMap(project, bars) {
  return (project.tracks || []).map((t) => {
    const on = new Array(bars).fill(false);
    for (const c of project.clips || []) {
      if (c.trackId !== t.id) continue;
      for (let b = Math.floor(c.start / 4); b < Math.ceil((c.start + c.len) / 4) && b < bars; b++) on[b] = true;
    }
    const runs = [];
    for (let b = 0; b < bars; b++) {
      if (!on[b]) continue;
      if (runs.length && runs[runs.length - 1][0] + runs[runs.length - 1][1] === b) runs[runs.length - 1][1]++;
      else runs.push([b, 1]);
    }
    return [t.color || '#9d97b8', runs];
  }).filter((r) => r[1].length);
}

function check(catalog) {
  const seen = new Set();
  for (const c of catalog) {
    const where = 'examples/catalog.json, "' + (c.id || c.title) + '": ';
    if (!ID.test(c.id || '')) throw new Error(where + 'id must be lowercase letters, digits and dashes');
    if (seen.has(c.id)) throw new Error(where + 'id is used twice');
    seen.add(c.id);
    for (const k of ['file', 'title', 'style', 'blurb']) if (!c[k]) throw new Error(where + k + ' is missing');
    if (!/^\d{4}-\d{2}-\d{2}$/.test(c.added || '')) throw new Error(where + 'added must be a date like 2026-11-26');
    if (!Array.isArray(c.tags) || !c.tags.length || c.tags.some((t) => typeof t !== 'string' || t !== t.toLowerCase().trim() || !t))
      throw new Error(where + 'tags must be a list of one or more lowercase words');
  }
}

/* -> { 'index.js': text, 'songs/<id>.js': text, ... } */
function build(catalog = readCatalog()) {
  check(catalog);
  const out = {};
  const index = catalog.map((c) => {
    const project = JSON.parse(fs.readFileSync(path.join(dir, c.file), 'utf8'));
    const end = (project.clips || []).reduce((a, x) => Math.max(a, x.start + x.len), 0);
    const bars = Math.ceil(end / 4);
    out['songs/' + c.id + '.js'] = HEAD + 'window.BDJ = window.BDJ || {};\n(BDJ.EXAMPLE_SONGS = BDJ.EXAMPLE_SONGS || {})[' +
      JSON.stringify(c.id) + '] = ' + JSON.stringify(project) + ';\n';
    return {
      id: c.id, title: c.title, style: c.style, blurb: c.blurb, tags: c.tags, added: c.added,
      bpm: project.bpm, tempoChanges: (project.tempo || []).length, root: project.root, scale: project.scale,
      bars, secs: songSecs(project, end), tracks: (project.tracks || []).length, map: songMap(project, bars),
    };
  });
  out['index.js'] = HEAD + 'window.BDJ = window.BDJ || {};\nBDJ.EXAMPLE_INDEX = ' + JSON.stringify(index) + ';\n';
  return out;
}

if (require.main === module) {
  const files = build();
  const songsDir = path.join(dir, 'songs');
  fs.mkdirSync(songsDir, { recursive: true });
  // songs no longer in the catalog go away
  for (const f of fs.readdirSync(songsDir)) if (!files['songs/' + f]) fs.unlinkSync(path.join(songsDir, f));
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(dir, name), text);
  console.log('wrote examples/index.js and ' + (Object.keys(files).length - 1) + ' songs in examples/songs/');
}
module.exports = { build };
