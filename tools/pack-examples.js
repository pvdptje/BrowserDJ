/* Packs examples/*.browserdj.json (listed in examples/catalog.json) into examples/examples.js.
   The page loads that script when the example picker opens; a script (unlike fetch) also works when
   index.html is opened straight from disk. Run after changing an example:  node tools/pack-examples.js */
'use strict';
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'examples');
const catalog = JSON.parse(fs.readFileSync(path.join(dir, 'catalog.json'), 'utf8'));

function build() {
  const list = catalog.map((c) => {
    const project = JSON.parse(fs.readFileSync(path.join(dir, c.file), 'utf8'));
    const end = (project.clips || []).reduce((a, x) => Math.max(a, x.start + x.len), 0);
    // follow the song's tempo changes: from beat b on it plays at bpm
    const changes = (project.tempo || []).filter((c) => c.b < end).sort((x, y) => x.b - y.b);
    let secs = 0, at = 0, bpm = project.bpm;
    for (const c of changes) { secs += ((c.b - at) * 60) / bpm; at = c.b; bpm = c.bpm; }
    secs = Math.round(secs + ((end - at) * 60) / bpm);
    return { id: c.id, title: c.title, style: c.style, blurb: c.blurb, bpm: project.bpm, bars: Math.ceil(end / 4), secs, project };
  });
  return '/* Generated by tools/pack-examples.js from examples/catalog.json and the .browserdj.json files. Do not edit. */\n' +
    'window.BDJ = window.BDJ || {};\nBDJ.EXAMPLES = ' + JSON.stringify(list) + ';\n';
}

if (require.main === module) {
  fs.writeFileSync(path.join(dir, 'examples.js'), build());
  console.log('wrote examples/examples.js with ' + catalog.length + ' songs');
}
module.exports = { build };
